using System.Reflection;

namespace Shos.WpfCadSample.Tests.Architecture;

/// <summary>
/// T-ARC：構造の確認（テスト計画書 4.14）
/// </summary>
public class ArchitectureTests
{
    const string rootNamespace = "Shos.WpfCadSample";

    // 設計書 3.2 で定めた、Core の namespace
    static readonly string[] coreNamespaces = [
        "Shos.WpfCadSample.Models",
        "Shos.WpfCadSample.Models.Geometry",
        "Shos.WpfCadSample.Controllers",
        "Shos.WpfCadSample.ViewModels",
        "Shos.WpfCadSample.Serialization",
        "Shos.WpfCadSample.Settings",
        "Shos.WpfCadSample.Services"
    ];

    static readonly string[] wpfAssemblyNames = ["PresentationFramework", "PresentationCore", "WindowsBase", "System.Xaml"];

    // コンパイラーやソースジェネレーターが生成した型は、構造の規則の対象外とする
    static readonly string[] generatedCodeAttributeNames = ["CompilerGeneratedAttribute", "GeneratedCodeAttribute"];

    // Microsoft.NET.Test.Sdk がテストプロジェクトのグローバル名前空間に生成するエントリポイント。
    // 生成コードを示す属性を持たないため、名前で除く
    const string testSdkEntryPointName = "AutoGeneratedProgram";

    static Assembly CoreAssembly => Assembly.Load("Shos.WpfCadSample.Core");
    static Assembly TestsAssembly => typeof(ArchitectureTests).Assembly;

    // T-ARC-01
    [Fact]
    public void CoreTypes_BelongToDesignedNamespaces()
    {
        var misplacedTypeNames = WrittenTypes(CoreAssembly)
            .Where(type => type.Namespace is not { } name || !coreNamespaces.Contains(name))
            .Select(type => type.FullName);

        Assert.Empty(misplacedTypeNames);
    }

    // T-ARC-02
    [Fact]
    public void CoreAssembly_DoesNotReferenceWpf()
    {
        var referencedNames = CoreAssembly.GetReferencedAssemblies().Select(name => name.Name ?? "");

        Assert.DoesNotContain(referencedNames, name => wpfAssemblyNames.Contains(name));
    }

    // T-ARC-04（ルート namespace 直下の禁止も、Core と Tests の両方で確かめる）
    [Fact]
    public void CoreAndTestsTypes_AreInNeitherGlobalNorRootNamespace()
    {
        var misplacedTypeNames = new[] { CoreAssembly, TestsAssembly }
            .SelectMany(WrittenTypes)
            .Where(type => type.Namespace is null or rootNamespace)
            .Select(type => type.FullName);

        Assert.Empty(misplacedTypeNames);
    }

    static IEnumerable<Type> WrittenTypes(Assembly assembly)
        => assembly.GetTypes().Where(type => !IsGenerated(type));

    // 生成された型の入れ子の型（例：<PrivateImplementationDetails> の中の型）は、自身には属性を持たないため、外側の型でも判定する
    static bool IsGenerated(Type type)
        => type.FullName == testSdkEntryPointName ||
           type.CustomAttributes.Any(attribute => generatedCodeAttributeNames.Contains(attribute.AttributeType.Name)) ||
           (type.DeclaringType is { } declaringType && IsGenerated(declaringType));
}
